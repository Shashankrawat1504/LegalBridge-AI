/**
 * Returns the Hindi intent key based on a query string (mirrors fallbackGuidance.ts logic).
 */
export function getHindiIntentKey(query: string): string {
  const q = query.toLowerCase().trim();
  if (
    q.includes('deposit') || q.includes('landlord') || q.includes('tenant') ||
    q.includes('rent') || q.includes('lease') || q.includes('evict')
  ) return 'deposit';
  if (
    q.includes('salary') || q.includes('wage') || q.includes('unpaid') ||
    q.includes('employer') || q.includes('boss') || q.includes('fnf') ||
    q.includes('resignation') || q.includes('fired') || q.includes('termination')
  ) return 'salary';
  if (
    q.includes('upi') || q.includes('cyber') || q.includes('fraud') ||
    q.includes('otp') || q.includes('scam') || q.includes('phishing') ||
    q.includes('debit') || q.includes('hacked')
  ) return 'upi';
  if (
    q.includes('consumer') || q.includes('refund') || q.includes('defective') ||
    q.includes('product') || q.includes('warranty') || q.includes('ecommerce') ||
    q.includes('amazon') || q.includes('flipkart')
  ) return 'consumer';
  if (
    q.includes('neighbour') || q.includes('neighbor') || q.includes('noise') ||
    q.includes('harassment') || q.includes('loud') || q.includes('fighting')
  ) return 'neighbour';
  if (
    q.includes('notice') || q.includes('summons') || q.includes('court paper') ||
    q.includes('lawyer notice')
  ) return 'notice';
  if (
    q.includes('workplace') || q.includes('unfair') || q.includes('discrimination') ||
    q.includes('posh')
  ) return 'workplace';
  return 'general';
}

/**
 * Returns Hindi CitizenGuidance for a given query.
 * Falls back to 'general' if no specific match found.
 */
export function getHindiGuidance(query: string): CitizenGuidanceHi {
  const key = getHindiIntentKey(query);
  return HINDI_GUIDANCE[key] ?? HINDI_GUIDANCE['general'];
}
